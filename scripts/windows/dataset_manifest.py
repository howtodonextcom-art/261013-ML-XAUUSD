"""Generates docs/data/DATASET_MANIFEST.md from data/store/manifest.sqlite (no account data; counts, ranges, checksums policy)."""
import datetime as dt
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "services" / "gateway"))
from xau_gateway.storage import Store

store = Store(ROOT / "data" / "store")
db = sqlite3.connect(store.db_path)
f = lambda ms, unit=1000: dt.datetime.fromtimestamp(ms / unit, dt.UTC).strftime("%Y-%m-%d %H:%M")
rows = db.execute("""SELECT kind, source_id, server, symbol,
                     SUM(CASE WHEN superseded=0 THEN 1 ELSE 0 END), SUM(CASE WHEN superseded=0 THEN rows ELSE 0 END),
                     MIN(CASE WHEN superseded=0 THEN min_key END), MAX(CASE WHEN superseded=0 THEN max_key END),
                     SUM(superseded), SUM(CASE WHEN quality!='' THEN 1 ELSE 0 END) FROM files GROUP BY 1,2,3,4 ORDER BY 1,2""").fetchall()
size = sum(p.stat().st_size for p in (store.root).rglob("*.parquet"))
q = db.execute("SELECT kind, reason, COUNT(*) FROM quarantine GROUP BY 1,2").fetchall()
sess = db.execute("SELECT COUNT(*) FROM sessions").fetchone()[0]
meta = dict(db.execute("SELECT k, v FROM meta WHERE k LIKE 'symbol:%' OR k='schema_version'"))
out = ["# DATASET MANIFEST", "", f"Generated by scripts/windows/dataset_manifest.py on {dt.date.today()} from `data/store/manifest.sqlite`.",
       f"Schema version {meta.get('schema_version')}, dataset version `ds-0.2`. Parquet on disk: {size / 1e6:.1f} MB. Capture sessions recorded: {sess}.",
       f"Symbol metadata: {', '.join(f'{k}={v}' for k, v in meta.items() if k.startswith('symbol:'))}.", "",
       "Times are MT5 **server time** (UTC+3 observed). `time_msc`-keyed kinds show ms keys converted; bar kinds show seconds.", "",
       "| kind | source_id | server | symbol | active files | active rows | first | last | superseded files (kept on disk) | files with quality note |", "|---|---|---|---|---|---|---|---|---|---|"]
for kind, src, srv, sym, nf, nr, lo, hi, sup, qn in rows:
    unit = 1000 if kind == "ticks" else 1
    out.append(f"| {kind} | {src} | {srv} | {sym} | {nf} | {nr} | {f(lo, unit)} | {f(hi, unit)} | {sup} | {qn} |")
out += ["", "## Quarantine table", "", "| kind | reason | count |", "|---|---|---|"] + [f"| {k} | {r} | {n} |" for k, r, n in q]
out += ["", "## Integrity", f"`Store.verify()` problems: {store.verify() or 'none (every manifest file exists and matches its sha256)'}", "",
        "## Policy", "- Raw ticks immutable; historical chunks re-fetched with different content are superseded, never deleted.",
        "- Live chunks carry `capture_session_id` and are never superseded. Chunks written before sessions existed are labelled `LEGACY_PRE_SESSION`.",
        "- `data/store` is git-ignored: this manifest is the public summary of what exists locally.", ""]
Path(ROOT / "docs" / "data" / "DATASET_MANIFEST.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out[:22]))
